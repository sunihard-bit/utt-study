#!/usr/bin/env python3
"""Generate trace tables by really running each program in Python 3.

Reads tools/traces.json  ->  writes src/15-traces.js  (const TRACES = {...})
Each trace: {"code": "...", "inputs": ["5", "3"], "cols": ["n", "total"]}
A row is recorded whenever a tracked variable changes, a condition (if/elif/while) is tested, or something is printed.
Row = {"l": line number (1-based), "v": {var: new value}, "c": [condition text, True/False] or null, "o": printed text}
"""
import io, json, pathlib, sys, builtins, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
specs = json.loads((ROOT / "tools" / "traces.json").read_text())

def fmt(v):
    if isinstance(v, str): return repr(v) if v == "" else v
    if isinstance(v, float) and v.is_integer(): return f"{v:.1f}"
    return str(v)

def run(spec):
    code, cols = spec["code"], spec["cols"]
    lines = code.split("\n")
    inputs = list(spec.get("inputs", []))
    out = io.StringIO()
    g = {"__builtins__": builtins}
    rows, prev = [], {}
    state = {"pending": None}
    real_input = builtins.input
    def fake_input(prompt=""):
        return inputs.pop(0)
    def snapshot():
        return {k: g[k] for k in cols if k in g}
    def flush(line_after):
        # record the effect of the line that just finished
        pend = state["pending"]
        if pend is None: return
        ln = pend
        now = snapshot(); changed = {k: fmt(v) for k, v in now.items() if k not in prev or prev[k] != v or type(prev[k]) != type(v)}
        text = out.getvalue(); o = text[state.get("olen", 0):]; state["olen"] = len(text)
        if changed or o:
            rows.append({"l": ln, "v": changed, "c": None, "o": o.rstrip("\n")})
        prev.clear(); prev.update(now)
    def tracer(frame, event, arg):
        if frame.f_code.co_filename != "<prog>": return tracer
        if event == "line":
            flush(frame.f_lineno)
            ln = frame.f_lineno; src = lines[ln-1].strip()
            m = re.match(r"^(if|elif|while)\s+(.*):\s*$", src)
            if m:
                try: val = eval(m.group(2), g)
                except Exception: val = None
                if val is not None: rows.append({"l": ln, "v": {}, "c": [m.group(2), bool(val)], "o": ""})
            state["pending"] = ln
        return tracer
    builtins.input = fake_input
    old = sys.stdout; sys.stdout = out
    try:
        sys.settrace(tracer); exec(compile(code, "<prog>", "exec"), g)
    finally:
        sys.settrace(None); sys.stdout = old; builtins.input = real_input
    flush(None)
    # merge consecutive output-only rows from the same line? keep simple: drop empty rows
    rows = [r for r in rows if r["v"] or r["c"] or r["o"]]
    return {"code": code, "inputs": spec.get("inputs", []), "cols": cols, "rows": rows, "output": out.getvalue().rstrip("\n")}

result = {k: run(v) for k, v in specs.items()}
js = "/* Generated by tools/trace.py from tools/traces.json: every row comes from really running the code in Python 3. Do not edit by hand. */\nconst TRACES = " + json.dumps(result, indent=0, ensure_ascii=False) + ";\n"
(ROOT / "src" / "15-traces.js").write_text(js)
for k, v in result.items():
    print(f"{k}: {len(v['rows'])} rows, output {v['output']!r}")
